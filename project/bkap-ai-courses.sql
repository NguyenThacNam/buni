-- ================================================================
-- 5. BẢNG REFRESH TOKEN
-- ================================================================
-- Access token là JWT, stateless — server không lưu gì nên KHÔNG thu hồi được,
-- lộ ra là dùng được tới khi hết hạn. Vì vậy access token để hạn rất ngắn
-- (15 phút), còn refresh token thì lưu ở đây để có thể thu hồi thật khi người
-- dùng đăng xuất.
--
-- Lưu HASH chứ không lưu token thô: đọc được bảng này mà token còn nguyên dạng
-- thì mạo danh được bất kỳ ai. Cùng lý do với việc băm mật khẩu.
--
-- revoked_at khác NULL nghĩa là token đã bị thu hồi. Giữ lại dòng thay vì xóa
-- để còn lần được dấu vết khi cần điều tra.
CREATE TABLE refresh_token (
    id          INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INTEGER      NOT NULL,
    token_hash  VARCHAR(64)  NOT NULL UNIQUE,
    expires_at  TIMESTAMP    NOT NULL,
    revoked_at  TIMESTAMP    NULL,
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE INDEX idx_refresh_token_user ON refresh_token(user_id);
