-- Xóa theo thứ tự ngược với khóa ngoại
DROP TABLE IF EXISTS Enrollment CASCADE;
DROP TABLE IF EXISTS Course CASCADE;
DROP TABLE IF EXISTS Category CASCADE;
DROP TABLE IF EXISTS users CASCADE;

-- ================================================================
-- HÀM TRIGGER: thay thế cho "ON UPDATE NOW()" của MySQL
-- PostgreSQL không hỗ trợ mệnh đề này ở mức cột.
-- ================================================================
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION set_last_studied_at() RETURNS TRIGGER AS $$
BEGIN
    NEW.last_studied_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ================================================================
-- 1. BẢNG NGƯỜI DÙNG
-- Tên bảng là "users": USER là từ khóa dành riêng của PostgreSQL.
-- ================================================================
CREATE TABLE users (
    id          INTEGER         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fullname    VARCHAR(100)    NOT NULL,
    email       VARCHAR(150)    NOT NULL UNIQUE,
    username    VARCHAR(50)     NOT NULL UNIQUE,
    phone       VARCHAR(10)     NOT NULL UNIQUE,
    password    VARCHAR(255)    NOT NULL,
    birthday    VARCHAR(12)     NOT NULL,
    role        VARCHAR(20)     NOT NULL DEFAULT 'STUDENT'
                                CHECK (role IN ('STUDENT','ADMIN')),
    createDate  TIMESTAMP       DEFAULT CURRENT_TIMESTAMP,
    last_login  TIMESTAMP       NULL,
    last_logout TIMESTAMP       NULL,
    is_online   BOOLEAN         DEFAULT FALSE
);

-- ================================================================
-- 2. BẢNG DANH MỤC KHÓA HỌC
-- ================================================================
CREATE TABLE Category (
    id          INTEGER         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100)    NOT NULL,
    slug        VARCHAR(100)    NOT NULL UNIQUE,
    status      VARCHAR(20)     NOT NULL DEFAULT 'active',
    prioty      INTEGER         NOT NULL DEFAULT 0,

    -- Danh mục bên Moodle xếp thành cây. parent_id ghi lại danh mục này nằm
    -- trong danh mục nào; để trống nghĩa là danh mục gốc.
    -- Ví dụ: "Chuyển đổi số cho cơ quan Đảng" nằm trong "Chuyển đổi số".
    parent_id          INTEGER  NULL REFERENCES category(id),

    -- Đối chiếu với danh mục bên Moodle, để lần đồng bộ sau biết bản ghi nào
    -- ứng với danh mục nào thay vì so theo tên.
    moodle_category_id INTEGER  NULL,

    created_at  TIMESTAMP       DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP       DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX idx_category_moodle ON category(moodle_category_id)
    WHERE moodle_category_id IS NOT NULL;

CREATE TRIGGER category_set_updated_at
    BEFORE UPDATE ON Category
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ================================================================
-- 3. BẢNG KHÓA HỌC
-- is_pro dùng SMALLINT chứ không phải BOOLEAN vì entity Course khai kiểu Integer.
-- ================================================================
CREATE TABLE Course (
    id                  INTEGER         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id         INTEGER         NOT NULL,
    instructor_id       INTEGER         NOT NULL,
    title               VARCHAR(200)    NOT NULL,
    slug                VARCHAR(200)    NOT NULL UNIQUE,
    subtitle            VARCHAR(300),
    description         TEXT,
    thumbnail_url       VARCHAR(500),
    preview_video_url   VARCHAR(500),
    level               VARCHAR(20)     DEFAULT 'ALL'
                                        CHECK (level IN ('BEGINNER','INTERMEDIATE','ADVANCED','ALL')),
    is_pro              SMALLINT        DEFAULT 0,
    price               NUMERIC(12,0)   DEFAULT 0,
    original_price      NUMERIC(12,0)   DEFAULT 0,
    price_type          VARCHAR(20)     DEFAULT 'PAID'
                                        CHECK (price_type IN ('PAID','FREE','CONTACT')),
    rating              NUMERIC(2,1)    DEFAULT 0,
    rating_count        INTEGER         DEFAULT 0,
    student_count       INTEGER         DEFAULT 0,
    lesson_count        INTEGER         DEFAULT 0,
    duration_text       VARCHAR(50),

    -- Khóa học tương ứng bên Moodle. Lưu ID số lấy từ URL /course/view.php?id=...
    -- Cố ý KHÔNG dùng slug đối chiếu idnumber bên Moodle: slug sửa được trong
    -- trang admin, đổi một cái là liên kết đứt âm thầm. ID thì lưu riêng, không
    -- phụ thuộc gì vào slug.
    -- NULL = chưa mở trên LMS, nút "Đăng ký học" sẽ hiện "Sắp khai giảng".
    moodle_course_id    INTEGER,

    -- Khóa đồng bộ từ LMS về mặc định là 'inactive': lúc đó chưa có giá, chưa
    -- phân loại đúng, hiện ngay ra trang chủ thì khách thấy một khóa nham nhở.
    -- Admin điền xong mới chuyển sang 'active'.
    status              VARCHAR(20)     NOT NULL DEFAULT 'active',

    created_at          TIMESTAMP       DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP       DEFAULT CURRENT_TIMESTAMP,

    FOREIGN KEY (category_id)   REFERENCES Category(id),
    FOREIGN KEY (instructor_id) REFERENCES users(id)
);

CREATE TRIGGER course_set_updated_at
    BEFORE UPDATE ON Course
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Mỗi khóa bên Moodle chỉ được nối với đúng một khóa bên buni. Không có ràng
-- buộc này thì hai khóa cùng trỏ vào một khóa LMS, ghi danh sẽ loạn.
-- Dùng chỉ mục có điều kiện vì cột cho phép NULL, mà nhiều khóa chưa nối thì
-- đều NULL — NULL không tính là trùng.
CREATE UNIQUE INDEX idx_course_moodle ON course(moodle_course_id)
    WHERE moodle_course_id IS NOT NULL;

-- ================================================================
-- 4. BẢNG ĐĂNG KÝ KHÓA HỌC & TIẾN ĐỘ
-- ================================================================
CREATE TABLE Enrollment (
    id               INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          INTEGER      NOT NULL,
    course_id        INTEGER      NOT NULL,
    status           VARCHAR(20)  NOT NULL DEFAULT 'ENROLLED'
                                  CHECK (status IN ('ENROLLED','IN_PROGRESS','COMPLETED')),
    progress_percent INTEGER      DEFAULT 0,
    enrolled_at      TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
    last_studied_at  TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT unique_user_course UNIQUE (user_id, course_id),
    FOREIGN KEY (user_id)   REFERENCES users(id)  ON DELETE CASCADE,
    FOREIGN KEY (course_id) REFERENCES Course(id) ON DELETE CASCADE
);

CREATE TRIGGER enrollment_set_last_studied_at
    BEFORE UPDATE ON Enrollment
    FOR EACH ROW EXECUTE FUNCTION set_last_studied_at();

